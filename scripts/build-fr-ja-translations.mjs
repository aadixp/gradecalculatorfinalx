async function updateUi() {
  const currentUiModule = await import('../src/i18n/ui.ts');
  const currentUi = currentUiModule.ui;
  const languages = currentUiModule.languages;
  const defaultLang = currentUiModule.defaultLang;

  const finalUi = {};

  for (const lang of Object.keys(languages)) {
    finalUi[lang] = {
      ...(currentUi[lang] || {})
    };
  }

  // Merge French and Japanese translations
  for (const [k, v] of Object.entries(frTranslations)) {
    finalUi.fr[k] = v;
  }
  for (const [k, v] of Object.entries(jaTranslations)) {
    finalUi.ja[k] = v;
  }

  // Format as TypeScript output
  const tsContent = `export const languages = ${JSON.stringify(languages, null, 2)} as const;

export type Lang = keyof typeof languages;

export const defaultLang: Lang = 'en';

export const ui: Record<Lang, Record<string, string>> = ${JSON.stringify(finalUi, null, 2)};
`;

  fs.writeFileSync(uiPath, tsContent, 'utf8');
  console.log('✅ Successfully updated src/i18n/ui.ts with complete FR and JA translations!');
}

updateUi().catch(console.error);
